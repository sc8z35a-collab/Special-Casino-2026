// Record only the models that have actually been imported. Missing originals
// retain the existing 2D artwork. Regenerate after adding further stages.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const model = (name) => fs.existsSync(path.join(root, 'img/3d/tree', name)) ? name : null;
const files = {
  stages: Array.from({ length: 9 }, (_, i) => model('stage-' + (i + 1) + '.glb')),
  seed: model('seed.glb'), preview: model('preview.glb'), soil: model('soil.glb'), fertilizer: model('fertilizer.glb')
};
fs.writeFileSync(path.join(root, 'js/art/tree-models.js'),
  '/* Generated by tools/3d/tree-manifest.mjs. */\n' +
  '(function (BR) { BR.TREE_MODELS = ' + JSON.stringify(files) + '; })(window.BR = window.BR || {});\n');

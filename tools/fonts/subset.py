"""Builds the small web fonts in fonts/ from the Google Fonts sources (OFL).

    python3 tools/fonts/subset.py

Only the characters actually used by the game are kept (collected from
index.html, js/, css/ and the server's messages in server/core/), so the
Japanese font stays tiny.  Source fonts are
downloaded to tools/fonts/src/ on first run (not committed).
"""
import glob
import os
import re
import urllib.request

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(HERE, 'src')
OUT = os.path.join(ROOT, 'fonts')
BASE = 'https://raw.githubusercontent.com/google/fonts/main/ofl/'
SOURCES = {
    'NotoSansJP.ttf': 'notosansjp/NotoSansJP%5Bwght%5D.ttf',
    'Exo2.ttf': 'exo2/Exo2%5Bwght%5D.ttf',
    'Montserrat.ttf': 'montserrat/Montserrat%5Bwght%5D.ttf',
}

# family, source, weights, extra charset rule
FACES = [
    ('NotoJP', 'NotoSansJP.ttf', (500, 700), 'all'),
    ('Exo2', 'Exo2.ttf', (600, 700, 800), 'latin'),
    ('MontserratX', 'Montserrat.ttf', (800, 900), 'title'),
]


def fetch():
    os.makedirs(SRC, exist_ok=True)
    for name, rel in SOURCES.items():
        dst = os.path.join(SRC, name)
        if not os.path.exists(dst):
            print('downloading', rel)
            urllib.request.urlretrieve(BASE + rel, dst)


def used_chars():
    # server/core holds the messages the server sends back (errors, notices)
    files = ([os.path.join(ROOT, 'index.html')] + glob.glob(os.path.join(ROOT, 'js', '**', '*.js'), recursive=True)
             + glob.glob(os.path.join(ROOT, 'css', '*.css')) + glob.glob(os.path.join(ROOT, 'server', 'core', '*.js')))
    chars = set()
    for f in files:
        if f.endswith(os.path.join('art', 'symbols.js')) or f.endswith(os.path.join('art', 'pattern.js')):
            continue
        txt = open(f, encoding='utf-8').read()
        txt = re.sub(r'\\u([0-9a-fA-F]{4})', lambda m: chr(int(m.group(1), 16)), txt)
        chars.update(ch for ch in txt if ord(ch) > 0x7f)
    ascii_ = {chr(c) for c in range(0x20, 0x7f)}
    return ''.join(sorted(chars | ascii_ | set('…・ー！？：　、。「」（）')))


def build():
    fetch()
    os.makedirs(OUT, exist_ok=True)
    allchars = used_chars()
    latin = ''.join(chr(c) for c in range(0x20, 0x7f)) + '×・'
    title = 'BIGWNSUPERMEAJCKOTXYLDHVF!0123456789 '
    css = ['/* Generated by tools/fonts/subset.py - subsets of OFL fonts (see fonts/LICENSE-OFL.txt). */']
    for family, src, weights, rule in FACES:
        text = {'all': allchars, 'latin': latin, 'title': title}[rule]
        for w in weights:
            font = TTFont(os.path.join(SRC, src))
            inst = instancer.instantiateVariableFont(font, {'wght': w}, updateFontNames=False)
            opts = subset.Options()
            opts.flavor = 'woff2'
            opts.layout_features = ['kern', 'liga', 'palt', 'tnum', 'pnum', 'locl', 'ccmp']
            opts.name_IDs = ['*']
            opts.notdef_outline = True
            sub = subset.Subsetter(opts)
            sub.populate(text=text)
            sub.subset(inst)
            fn = f'{family}-{w}.woff2'
            inst.flavor = 'woff2'
            inst.save(os.path.join(OUT, fn))
            size = os.path.getsize(os.path.join(OUT, fn))
            print(f'{fn}: {size // 1024} KiB ({len(text)} chars)')
            css.append("@font-face { font-family: '%s'; src: url('../fonts/%s') format('woff2'); font-weight: %d; font-style: normal; font-display: block; }" % (family, fn, w))
    with open(os.path.join(ROOT, 'css', 'fonts.css'), 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(css) + '\n')


if __name__ == '__main__':
    build()

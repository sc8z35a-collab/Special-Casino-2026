"""Regenerates the generated art modules in js/art/ from the Python sources.

    python3 tools/art/build.py

The reel symbols are images (see tools/art/symbol_images.py); this script
builds the vector background pattern, js/art/pattern.js.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
ROOT = os.path.dirname(os.path.dirname(HERE))

import pattern  # noqa: E402


def write_module(name, var, mapping):
    out = os.path.join(ROOT, 'js', 'art', name)
    body = ',\n'.join(f'    {json.dumps(k)}: {json.dumps(v)}' for k, v in mapping.items())
    src = ('/* Generated by tools/art/build.py - do not edit by hand. */\n'
           '(function (BR) {\n'
           f'  BR.{var} = {{\n{body}\n  }};\n'
           '})(window.BR = window.BR || {});\n')
    with open(out, 'w', encoding='utf-8') as fh:
        fh.write(src)
    print(f'wrote {out} ({len(src) // 1024} KiB)')


def main():
    write_module('pattern.js', 'PATTERN', pattern.pattern_module())


if __name__ == '__main__':
    main()
